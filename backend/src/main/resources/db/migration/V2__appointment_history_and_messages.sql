ALTER TABLE queue_entries ADD COLUMN cancellation_reason VARCHAR(500);

CREATE TABLE appointment_messages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  queue_entry_id BIGINT NOT NULL REFERENCES queue_entries(id),
  author_id BIGINT NOT NULL REFERENCES users(id),
  body VARCHAR(1000) NOT NULL,
  created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_messages_queue_created ON appointment_messages(queue_entry_id, created_at);
